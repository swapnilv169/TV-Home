#!/usr/bin/env python3
"""Generate the Java cleanup catalog from the same JSON the computer helper reads."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'launcher/common/cleanup-packages.json'
TARGET = ROOT / 'launcher/common/src/main/java/com/veyra/shared/CleanupCatalog.java'

def generated():
    values = json.loads(SOURCE.read_text(encoding='utf-8'))
    if not isinstance(values, dict) or not values:
        raise ValueError('Cleanup catalog must be a nonempty package/name object')
    lines = ['package com.veyra.shared;', '', 'import java.util.LinkedHashMap;', '',
             '/** Generated by tools/generate_cleanup.py; edit common/cleanup-packages.json. */',
             'public final class CleanupCatalog {', '    private CleanupCatalog() {}',
             '    public static LinkedHashMap<String,String> entries() {',
             '        LinkedHashMap<String,String> values = new LinkedHashMap<>();']
    for package, name in values.items():
        if not re.fullmatch(r'[a-zA-Z][a-zA-Z0-9_.]{1,180}', package) or not isinstance(name, str) or not name.strip() or any(ord(c) < 32 for c in name):
            raise ValueError('Invalid cleanup entry')
        lines.append(f'        values.put({json.dumps(package)}, {json.dumps(name)});')
    return '\n'.join(lines + ['        return values;', '    }', '}', ''])

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    expected = generated()
    if args.check:
        if not TARGET.is_file() or TARGET.read_text(encoding='utf-8') != expected:
            raise SystemExit('Cleanup catalog is out of date. Run python tools/generate_cleanup.py')
        print('Cleanup catalog matches its JSON source.')
    else:
        TARGET.parent.mkdir(parents=True, exist_ok=True)
        TARGET.write_text(expected, encoding='utf-8')
        print('Generated CleanupCatalog.java')
